"""The committed S1 primary-cause cells and S4's ungraded split (#310, D2 and D11).

``app_arm/cells.json`` is generated by ``python -m tadabur.followalong_audit strata`` (with S2's
oracle table) from the App word table and the detectors' re-grade at the pinned harness. It is the
artifact the pre-registration quotes: 14 primary-cause × base-flag cells with the 200-snip
allocation, each cell's inclusion probability, and how many S4 words had an ungraded detector.

The artifact is committed because neither number is recomputable from the other committed tables:
``pools.json``'s ``s1_by_cause_and_base`` counts a word once per cause (any-cause), and no
committed file holds per-word base flags or per-detector grading. The test pins the exact 14
values, the S4 split, and the document's agreement with them.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

from tadabur.followalong_audit.allocation import PRIMARY_CAUSES, allocate

ROOT = Path(__file__).resolve().parents[3]
AUDIT = ROOT / "tools" / "tadabur" / "followalong_audit"
CELLS = json.loads((AUDIT / "app_arm" / "cells.json").read_text(encoding="utf-8"))
PREREG = ROOT / "docs" / "followalong-audit-preregistration.md"

#: The cells as the strata re-grade at 028bc51 computes them over the *covered* words, the
#: Teacher-graded ones (words, snips). Amended by A1 (2026-11-24): the first version counted
#: every S1 word (5,156); the 459 the Teacher decode never graded left the frame.
EXPECTED_CELLS = {
    ("target_pair", False): (20, 3), ("target_pair", True): (41, 3),
    ("soft_pair", False): (105, 4), ("soft_pair", True): (344, 14),
    ("other_consonant", False): (915, 38), ("other_consonant", True): (1607, 67),
    ("shaddah", False): (45, 3), ("shaddah", True): (174, 7),
    ("tashkeel", False): (208, 9), ("tashkeel", True): (416, 17),
    ("skipped", False): (82, 4), ("skipped", True): (296, 12),
    ("unrecorded", False): (58, 3), ("unrecorded", True): (386, 16),
}
EXPECTED_S4 = {"words": 38598, "at_least_one_detector_ungraded": 2184,
               "all_four_detectors_ungraded": 57, "ungraded_pairs": 3059}
# Amended by A1: the covered words of S5 (candidate buckets 3,933 / 5,103 / 306).
EXPECTED_S5 = {"leading": (510, 10), "trailing": (549, 10), "interior": (148, 10)}


def _cells(line: str) -> list[str]:
    return [cell.strip().strip("`*") for cell in line.strip().strip("|").split("|")]


def _section(number: int) -> str:
    text = PREREG.read_text(encoding="utf-8")
    parts = re.split(r"^## (\d+)\. .*$", text, flags=re.M)
    return dict(zip(parts[1::2], parts[2::2]))[str(number)]


def _table_rows(section: str) -> list[list[str]]:
    return [_cells(line) for line in section.splitlines() if line.strip().startswith("|")]


def _int(cell: str) -> int:
    return int(cell.replace(",", ""))


def _doc_cells() -> dict[tuple[str, bool], list[str]]:
    return {(row[0], row[1] == "yes"): row for row in _table_rows(_section(3))
            if len(row) >= 5 and row[0] in PRIMARY_CAUSES and row[1] in ("yes", "no")}


def test_the_cells_record_holds_the_14_primary_cause_cells():
    cells = {(row["cause"], row["base_flags"]): row for row in CELLS["s1_primary_cells"]}
    assert set(cells) == set(EXPECTED_CELLS)
    assert {key: (row["words"], row["n"]) for key, row in cells.items()} == EXPECTED_CELLS


def test_the_cells_are_the_pre_registered_floor_and_largest_remainder_split():
    counts = {key: words for key, (words, _) in EXPECTED_CELLS.items()}
    assert sum(counts.values()) == 4697
    assert allocate(counts, 200, floor=3) == {key: n for key, (_, n) in EXPECTED_CELLS.items()}


def test_the_s4_split_is_the_committed_one():
    assert CELLS["s4"] == EXPECTED_S4
    assert CELLS["detector_ungraded"] == 39936


def test_the_doc_quotes_every_cell_and_its_inclusion_probability():
    quoted = _doc_cells()
    assert {key: (_int(row[2]), _int(row[3])) for key, row in quoted.items()} == EXPECTED_CELLS
    for key, row in quoted.items():
        words, n = EXPECTED_CELLS[key]
        assert row[4] == f"{n / words:.3g}", f"{key} inclusion probability"


def test_the_doc_quotes_s4s_ungraded_split_and_the_ungraded_pair_count():
    text = _section(3)
    assert f"{EXPECTED_S4['words']:,}" in text and "39,936" in text
    assert f"{EXPECTED_S4['at_least_one_detector_ungraded']:,}" in text
    assert f"{EXPECTED_S4['all_four_detectors_ungraded']:,}" in text
    assert re.search(r"at least one detector[^\n]*\d", text)
    assert re.search(r"all four detectors[^\n]*\d", text)


def test_the_doc_quotes_s5s_three_bucket_inclusion_probabilities():
    rows = {row[0]: row for row in _table_rows(_section(3))
            if len(row) >= 4 and row[0] in EXPECTED_S5}
    assert set(rows) == set(EXPECTED_S5)
    for bucket, (words, n) in EXPECTED_S5.items():
        assert (_int(rows[bucket][1]), _int(rows[bucket][2])) == (words, n)
        assert rows[bucket][3] == f"{n / words:.3g}"
