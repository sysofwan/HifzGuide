"""Render ``docs/consonant-round2-freeze.md`` from ``consonant2_readout/freeze.json`` (#227).

Every number is read from the record; the prose states only what the freeze's construction
fixes. The record is the tlog look gating set only: no confirm row was read, so nothing here is
a confirm-set reading, and the power line decides nothing.
"""

from __future__ import annotations

from collections.abc import Mapping, Sequence

from training.aug_readout_spec import C95
from training.consonant_freeze_doc import CAUSES_EXPLAINED


def _cell(entry: Mapping) -> str:
    return f"{entry['words']} ({entry['per_1000']:.2f})"


def _row(label: str, cells: Sequence[str]) -> str:
    return f"| {label} | " + " | ".join(cells) + " |"


def _separator(columns: int) -> str:
    return "|" + "---|" * columns


def _cause_table(record: Mapping) -> list[str]:
    models = record["models"]
    columns = tuple(models)
    return [
        _row("graded words",
             [str(models[m]["scorings"]["shipped_default"]["graded"]) for m in columns]),
        _row("false flags",
             [f"{models[m]['scorings']['shipped_default']['flagged']} "
              f"({models[m]['scorings']['shipped_default']['per_1000']:.2f})" for m in columns]),
        *[_row(cause, [_cell(models[m]["scorings"]["shipped_default"]["causes"][cause])
                       for m in columns])
          for cause in next(iter(models.values()))["scorings"]["shipped_default"]["causes"]],
    ]


def _substitution_table(record: Mapping) -> list[str]:
    c95 = record["models"][C95]["scorings"]["shipped_default"]
    out: list[str] = []
    for cause, rows in c95["substitutions"].items():
        out += ["", f"**{cause}**", ""]
        if not rows:
            out.append("No substitution carries this cause.")
            continue
        out += ["| substitution | words | per 1,000 |", _separator(3)]
        out += [f"| {row['substitution']} | {row['words']} | "
                f"{1000 * row['words'] / c95['graded']:.2f} |" for row in rows]
    return out


def render(record: Mapping) -> str:
    """The freeze's doc: the look gating cause split, C95's top substitutions, G5's frozen
    list, the ``د→ت`` reading, the power line, the graded-word coverage, and the inputs and
    pins that produced them."""
    models = record["models"]
    columns = tuple(models)
    out = [
        "# The tlog consonant round's frozen look readings (#227)",
        "",
        f"Generated by `{record['command']}` and "
        "`python -m training.consonant_readout doc --spec consonant2` from "
        "`tools/tadabur/consonant2_readout/freeze.json`; do not edit by hand.",
        "",
        "**The tlog look gating set only.** No confirm row was read: this record holds the "
        "look gating rows' grades, and the confirm tranches stay sealed until the pre-claim "
        "gates pass. It is the first grade of any round-2 tlog decode.",
        "",
        "A **false flag** is a word the app shows as not correct on a clip of presumed-correct "
        "recitation. tlog gating keeps real mistakes, so a flag here is presumed false; the "
        "catch-loss audit is what measures that. A word may carry more than one cause.",
        "",
        "The causes are `training.word_flags`'s: " + "; ".join(
            f"`{cause}` ({CAUSES_EXPLAINED[cause]})" for cause in
            models[C95]["scorings"]["shipped_default"]["causes"]) + ".",
        "",
        "## C95's false flags by cause on tlog look gating",
        "",
        "Counts, with the rate per 1,000 graded words in parentheses, at the shipped default. "
        "`#178` and the teacher are context columns; `h448` is not decoded on tlog.",
        "",
        "| cause | " + " | ".join(models[m]["label"] for m in columns) + " |",
        _separator(len(columns) + 1),
        *_cause_table(record),
        "",
        "## C95's top substitutions by cause",
        "",
        "The top ten substitutions behind C95's false-flagged look-gating words, by "
        "`word_flags.substitution_tally` (a word counts once per substitution), per cause; a "
        "shaddah deletion is its own cause and the madd alif (`ا→∅`) is counted "
        "(Muraja#263). An empty list means no substitution carries that cause.",
        *_substitution_table(record),
        "",
        "## G5's veto list, frozen before training",
        "",
        "C95's top ten consonant substitutions behind look-gating false-flagged words, the "
        "madd alif (`ا→∅`) aside, ties by substitution (Unicode order), "
        "**plus `د→ت`** — the owner kept it in the list whatever its rank "
        "(2026-10-24), and it is added once. G5 "
        "reads each substitution's flagged words per 1,000 on the pooled confirm set as "
        "**candidate minus C95** and fails if any paired 99.5% lower bound is above zero. It "
        "is a veto, not a detector.",
        "",
        "| substitution | cause | look-gating words |",
        "|---|---|---|",
        *[f"| {row['substitution']} | {row['cause'] or 'not observed'} | {row['words']} |"
          for row in record["substitutions"]],
        "",
        "## The `د→ت` reading",
        "",
        "C95 against #178 on the same look gating rows. Reported only: it changes neither the "
        "list above nor the bar. #178 carried 39 of these against C95's 29 on Tarteel v1 "
        "confirm, the likeliest non-tlog reason for this round to fail.",
        "",
        "| model | flagged words |",
        "|---|---|",
        *[f"| {models[m]['label']} | {row['words']} |"
          for m, row in record["dal_ta_reading"].items()],
        "",
        "## The one-tranche power line",
        "",
        f"**{record['power_check']['label']}.** The paired clustered standard error of "
        f"#178 − C95 per 1,000 graded words, from the look gating set's surah-clustered "
        f"bootstrap draw: all-cause "
        f"{record['power_check']['all_cause']['se']:.3f}, tashkeel "
        f"{record['power_check']['tashkeel']['se']:.3f}. Projections for the claimed tranches "
        "are in the pre-registration; this line measures one tranche and decides nothing.",
        "",
        "## Graded-word coverage",
        "",
        "The share of each model's placed look-gating words the engine grades: the measured "
        "replacement for the pre-registration's projected 0.98 graded share.",
        "",
        "| model | words | graded | graded share |",
        "|---|---|---|---|",
        *[f"| {models[m]['label']} | {row['words']} | {row['graded']} | "
          f"{row['graded_share']:.4f} |" for m, row in record["coverage"].items()],
        "",
        "## The inputs, harness and pins",
        "",
        "The freeze read three committed decode files:",
        "",
        "| input | SHA-256 |",
        "|---|---|",
        *[f"| `{name}` | `{digest}` |" for name, digest in record["inputs"].items()],
        "",
        f"{record['items']} tlog look gating clips were graded through the Muraja harness at "
        f"commit `{record['pins']['muraja_commit']}` (binary SHA-256 "
        f"`{record['pins']['harness_sha256']}`), whose build is recorded in the JSON. The "
        f"pre-registration doc's SHA-256 is `{record['pins']['prereg_sha256']}`.",
        "",
        "The record also holds each model's graded and flagged counts, every cause's count, "
        "the full substitution tally and the spans' coverage; re-run `doc` after any change to "
        "the prose.",
        "",
    ]
    return "\n".join(out)
