"""Render ``docs/consonant-round-freeze.md`` from ``consonant_readout/freeze.json`` (#177).

Every number is read from the record; the prose states only what the freeze's construction
fixes. The record is the look half only: the confirm half was never read, so nothing here is a
confirm-half reading. Nothing here sets a threshold.
"""

from __future__ import annotations

from collections.abc import Mapping, Sequence

#: How each ``word_flags`` cause is read, in plain language.
CAUSES_EXPLAINED = {
    "tashkeel": "a haraka mark the mushaf prescribes is missing or wrong",
    "soft_pair": "a consonant heard as its soft-pair partner; Muraja's soft-pair allowance "
                 "forgives these",
    "target_pair": "a consonant heard as one of the target pairs (ذ↔ظ, س↔ش, ط↔ق); the app "
                   "does not forgive these",
    "other_consonant": "any other consonant substitution, deletion included",
    "shaddah": "a doubled consonant collapsed into one",
    "skipped": "the app's skip marking passed the word over",
    "unrecorded": "the kept grade names no error, so the cause is unknown",
}


def _cell(entry: Mapping) -> str:
    return f"{entry['words']} ({entry['per_1000']:.2f})"


def _row(label: str, cells: Sequence[str]) -> str:
    return f"| {label} | " + " | ".join(cells) + " |"


def _cause_table(record: Mapping, scoring: str) -> list[str]:
    models = record["models"]
    columns = tuple(models)
    out = [_row("graded words",
                [str(models[m]["scorings"][scoring]["graded"]) for m in columns]),
           _row("false flags",
                [f"{models[m]['scorings'][scoring]['flagged']} "
                 f"({models[m]['scorings'][scoring]['per_1000']:.2f})" for m in columns])]
    causes = models["c95"]["scorings"][scoring]["causes"]
    out += [_row(cause, [_cell(models[m]["scorings"][scoring]["causes"][cause])
                         for m in columns])
            for cause in causes]
    return out


def _substitution_table(record: Mapping, scoring: str) -> list[str]:
    """C95's top ten substitutions for each consonant cause, with their look-half counts."""
    c95 = record["models"]["c95"]["scorings"][scoring]
    out: list[str] = []
    for cause, rows in c95["substitutions"].items():
        out += ["", f"**{cause}**", ""]
        if not rows:
            out.append("No substitution.")
            continue
        out += ["| substitution | words | per 1,000 |", "|---|---|---|"]
        out += [f"| {row['substitution']} | {row['words']} | "
                f"{1000 * row['words'] / c95['graded']:.2f} |" for row in rows]
    return out


def _model_header(record: Mapping) -> str:
    return "| cause | " + " | ".join(table["label"]
                                     for table in record["models"].values()) + " |"


def render(record: Mapping) -> str:
    """The freeze's doc: C95's look-half cause split with h448 and teacher columns, C95's top
    substitutions by cause, G5's frozen list, and the inputs and pins that produced them."""
    out = [
        "# The consonant round's frozen look-half readings (#177)",
        "",
        f"Generated by `{record['command']}` and "
        "`python -m training.consonant_readout doc` from "
        "`tools/tadabur/consonant_readout/freeze.json`; do not edit by hand.",
        "",
        "**C95, look half only.** The confirm half was not read: the freeze command refuses "
        "`--half confirm`, and this record holds only the look half of Tarteel v1.",
        "",
        "A **false flag** is a word the app shows as not correct on a clip of correct "
        "recitation. A word may carry more than one cause, so the causes can add up to more "
        "than the flagged words.",
        "",
        "The causes are `training.word_flags`'s: " + "; ".join(
            f"`{cause}` ({CAUSES_EXPLAINED[cause]})" for cause in
            record["models"]["c95"]["scorings"]["shipped_default"]["causes"]) + ".",
        "",
        "## C95's false flags by cause",
        "",
        "Counts, with the rate per 1,000 graded words in parentheses. `h448` and the teacher "
        "are read from their committed look-half decodes, for context only.",
        "",
        "### Shipped default",
        "",
        _model_header(record),
        "|---|---|---|---|",
        *_cause_table(record, "shipped_default"),
        "",
        "### Allowances off",
        "",
        _model_header(record),
        "|---|---|---|---|",
        *_cause_table(record, "allowances_off"),
        "",
        "## C95's top substitutions by cause",
        "",
        "The top ten substitutions behind C95's false-flagged look-half words, by "
        "`word_flags.substitution_tally` (a word counts once per substitution). The table "
        "covers the round's three consonant causes; `shaddah`, `tashkeel`, `skipped` and "
        "`unrecorded` carry no entry here. The madd alif (`ا→∅`) is counted in the split but "
        "is not a consonant substitution (Muraja#263).",
        "",
        "### Shipped default",
        *_substitution_table(record, "shipped_default"),
        "",
        "### Allowances off",
        *_substitution_table(record, "allowances_off"),
        "",
        "## G5's veto list, frozen before training",
        "",
        "The ten consonant substitutions behind the most C95 false-flagged words at the "
        "shipped default, the madd alif (`ا→∅`) aside; ties are broken by the substitution "
        "string (Unicode order), so the list is deterministic. G5 reads each one's flagged "
        "words per 1,000 on the confirm half and fails if a paired 99.5% lower bound is above "
        "zero. It is a veto, not a detector.",
        "",
        "| substitution | cause | look-half words |",
        "|---|---|---|",
        *[f"| {row['substitution']} | {row['cause']} | {row['words']} |"
          for row in record["substitutions"]],
        "",
        "## The inputs, harness and pins",
        "",
        "The freeze read three committed decode files:",
        "",
        "| input | SHA-256 |",
        "|---|---|",
        *[f"| `{name}` | `{digest}` |" for name, digest in record["inputs"].items()],
        "",
        f"{record['items']} Tarteel v1 look-half clips were graded through the Muraja harness "
        f"at commit `{record['pins']['muraja_commit']}` (binary SHA-256 "
        f"`{record['pins']['harness_sha256']}`), whose build is recorded in the JSON. The "
        f"pre-registration doc's SHA-256 is `{record['pins']['prereg_sha256']}`.",
        "",
        "The record also holds each model's graded and flagged counts and every cause's count "
        "and rate; re-run `doc` after any change to the prose.",
        "",
    ]
    return "\n".join(out)
