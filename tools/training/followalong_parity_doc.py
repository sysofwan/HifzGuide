def _table(header: list[str], rows: list[list[str]]) -> list[str]:
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    return lines + ["| " + " | ".join(row) + " |" for row in rows] + [""]


def render(report: dict) -> str:
    muraja = report["muraja"]
    pin, current = muraja["pin"], muraja["current"]
    logs = report["logs"]
    sessions = report["owner_sessions"]
    differences = [(row["session"], row["mode"], item) for row in sessions
                   for item in row["current_differences"]]
    log_rows = [[f"`{entry['log']}`", "none" if not entry["differences"] else "; ".join(entry["differences"])]
                for entry in logs]
    session_rows = [[row["session"], f"`{row['mode']}`", "yes" if row["pin_exact"] else "**no**",
                     str(len(row["current_differences"]))] for row in sessions]
    difference_rows = [[session, f"`{mode}`", item["word"], f"`{item['explained_by']}`"]
                       for session, mode, item in differences]
    difference_section = (_table(["session", "mode", "word", "explained by"], difference_rows)
                          if differences else ["No word's decision differs between the two commits.", ""])
    return "\n".join([
        "# Gate P1: the follow-along audit's replay parity (#306)",
        "",
        "Generated by `python -m training.followalong_parity <exports>` (from `tools/`); do not",
        "edit by hand. The machine-readable report is `tools/device_logs/parity_report.json`. The",
        "owner's exports are private: this note carries positions and counts only.",
        "",
        "The audit grades with today's app, `Muraja " + current + "` (v1.0.28). The pin",
        f"`{pin}` is the build every frozen readout was recorded with, and every frozen readout",
        "keeps it. Two gates are replayed here:",
        "",
        f"1. **Muraja's own logs.** All {len(logs)} logs in Muraja's `tools/test_logs` at",
        f"   `{current}` replay under the shipped default and reproduce the `baseline.json` that",
        "   ships with each (final position and every word's quality), exactly.",
        "2. **The owner's sessions.** The owner recorded these on app 1.0.27 (Muraja",
        f"   `{pin}`). Each reproduces every `Grade end word` decision the device logged, in its",
        "   own mode, with #153's lengthened previews. At the audit's commit every differing",
        "   decision is listed below with the 1.0.28 change that explains it.",
        "",
        "## Muraja's device logs at the audit's commit",
        "",
        f"{len(logs)} logs, each against its own baseline. A non-empty cell would block the",
        "re-pin; the comparison is not loosened.",
        "",
        *_table(["log", "differences"], log_rows),
        "## The owner's sessions",
        "",
        "`pin exact` is every device decision reproduced at the pin, in the session's recorded",
        "mode. Differences are the words whose kept status or logged decisions moved at the",
        "audit's commit.",
        "",
        *_table(["session", "mode", "pin exact", "differing words"], session_rows),
        "## Every differing decision at the audit's commit",
        "",
        *difference_section,
        "## The changes that explain a difference",
        "",
        "Each explanation comes from a mechanical rule in `training/followalong_parity.py`",
        "(`explain`), one rule per change. A difference no rule explains raises instead of being",
        "labelled.",
        "",
        *(f"- {CHANGE_NOTES[name]}" for name in CHANGES),
        "",
        "## Re-running",
        "",
        "```bash",
        "# from tools/, on a Mac: build the harness at both commits, then the gate",
        "bash muraja_harness/build.sh",
        f"bash muraja_harness/build.sh {current}",
        "python -m training.followalong_parity ~/Downloads/muraja-bug-report\\ {69,70,71}.txt",
        "```",
        "",
        "Harness builds the replay was made with: " + "; ".join(
            f"`{name}` at `{commit[:7]}`" for name, commit in (("pin", pin), ("audit", current))) + ".",
        "",
    ])


if __name__ == "__main__":
    import json

    from training.followalong_parity import DOC_PATH, REPORT_PATH

    DOC_PATH.write_text(render(json.loads(REPORT_PATH.read_text(encoding="utf-8"))), encoding="utf-8")
