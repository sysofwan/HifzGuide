"""Gate P1 of the follow-along audit (#306): Muraja's 74 device test logs replay exactly as their
baselines record at 028bc51, and the owner's three exports reproduce every device decision at
the pin they were recorded on (app 1.0.27 = 99c326f) with every difference at 028bc51 (app
1.0.28) explained by a named change. The committed report (``device_logs/parity_report.json``)
and note (``docs/followalong-audit-parity.md``) are generated by ``training.followalong_parity``;
the replay itself is gated in ``test_muraja_repin_harness.py``.

The report's shape::

    {"muraja": {"pin": <99c326f>, "current": <028bc51>},
     "logs": [{"log": <name>, "differences": [<str>...]}, ...],        # all 74, sorted by log
     "owner_sessions": [{"session": "69#1", "mode": "balanced"|"strict", "pin_exact": bool,
                         "current_differences": [{"word": "2:19:15", "explained_by": <CHANGES>}]}]}
"""

from __future__ import annotations

import json
import re

from training import followalong_parity as fp
from training import muraja_policy as mp
from training.followalong_parity_doc import render

REPORT = json.loads(fp.REPORT_PATH.read_text(encoding="utf-8"))
CURRENT = "028bc513eeb233caa7240a5c37c423da59f3d9d7"
#: The 1.0.28 changes (Muraja ``99c326f..028bc51``) a device decision may differ by.
NAMED_CHANGES = ("madd_alif", "tanween_at_waqf", "stop_pass", "error_indexing")


def test_the_explanations_a_difference_may_carry_are_muraja_s_four_grading_changes():
    assert tuple(fp.CHANGES) == NAMED_CHANGES


def test_the_report_names_the_pin_and_the_audits_commit():
    assert REPORT["muraja"] == {"pin": mp.MURAJA_COMMIT, "current": mp.CURRENT_COMMIT}
    assert mp.CURRENT_COMMIT == CURRENT


def test_all_74_logs_reproduce_their_baselines_at_the_current_commit():
    logs = REPORT["logs"]
    assert len(logs) == 74 and [e["log"] for e in logs] == sorted(e["log"] for e in logs)
    assert {e["log"] for e in logs} >= {"generated_surah2_page4_normal", "surah55_page533_qud_refrain_63"}
    assert [e["log"] for e in logs if e["differences"]] == []


def test_the_owner_sessions_reproduce_every_device_decision_at_the_pin_in_their_recorded_mode():
    sessions = {s["session"]: s for s in REPORT["owner_sessions"]}
    assert {name: s["mode"] for name, s in sessions.items()} == {
        "69#1": "balanced", "70#2": "strict", "71#2": "strict"}
    assert all(s["pin_exact"] is True for s in sessions.values())


def test_every_difference_at_the_current_commit_is_explained_by_a_named_change():
    differences = [d for s in REPORT["owner_sessions"] for d in s["current_differences"]]
    assert all(set(d) == {"word", "explained_by"} and d["explained_by"] in NAMED_CHANGES for d in differences)
    assert all(re.fullmatch(r"\d+:\d+:\d+", d["word"]) for d in differences)


def test_the_note_is_rendered_from_the_report_and_lists_every_difference():
    note = fp.DOC_PATH.read_text(encoding="utf-8")
    assert fp.DOC_PATH.name == "followalong-audit-parity.md" and fp.DOC_PATH.parent.name == "docs"
    assert note == render(REPORT)
    assert "74" in note and mp.CURRENT_COMMIT in note
    for s in REPORT["owner_sessions"]:
        assert s["session"] in note
        for d in s["current_differences"]:
            assert d["word"] in note and d["explained_by"] in note


def test_the_report_and_the_note_carry_positions_and_counts_only():
    """The owner's exports are private: no Arabic, no log text."""
    arabic = re.compile("[؀-ۿ]")
    assert not arabic.search(json.dumps(REPORT, ensure_ascii=False))
    assert not arabic.search(fp.DOC_PATH.read_text(encoding="utf-8"))
