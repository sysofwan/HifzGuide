"""Render `docs/zipformer-comparison.md` from the committed `report.json` (#245).

The page is a pure function of :data:`training.zipformer_readout.REPORT_PATH`: the readout writes
the record, this module renders it, and a test pins the committed page to the render. Every
number is the record's; the prose states the rule it is read under and the caveats the reports
on #245 fixed (the ratchet's asymmetry, the arms, the card baseline's protocol).
"""

from __future__ import annotations

from collections.abc import Mapping, Sequence

HEADER = """# The zipformer screen (#245)

Generated by `python -m training.zipformer_readout doc` from
`tools/tadabur/zipformer_screen/report.json`; do not edit by hand.

"""


def _cell(value) -> str:
    if value is None:
        return "—"
    if isinstance(value, float):
        return f"{value:.2f}"
    return str(value)


def _interval(row) -> str:
    if not row or not row.get("interval"):
        return ""
    low, high = row["interval"]["lower"], row["interval"]["upper"]
    return f" [{_cell(low)}, {_cell(high)}]"


def _counts(row) -> str:
    """A rate's whole-item counts (the sample arrays hold them as floats)."""
    return f"{row['num']:.0f}/{row['den']:.0f}"


def _table(header: Sequence[str], rows: Sequence[Sequence[str]]) -> str:
    return "\n".join(["| " + " | ".join(header) + " |",
                      "|" + "|".join("---" for _ in header) + "|",
                      *("| " + " | ".join(row) + " |" for row in rows)]) + "\n"


def _gates(record: Mapping) -> list[str]:
    gates = record["gates"]
    rows = []
    for name, gate in gates.items():
        if name == "parity":
            rows.append([name, "v3.2 fp32 vs sherpa-onnx 2.0.1", "PASS" if gate["passed"]
                         else "STOP", "—", "—"])
        else:
            per = gate["character_per"]
            scale = str(gate["pinned_scale"])
            roundtrip = gate["roundtrip"]
            failures = ", ".join(f"{kind}: {count}" for kind, count
                                 in roundtrip["failures"].items())
            rows.append([name, f"{gate['model']} ({gate['role']})",
                         "PASS" if gate["passed"] else ("baseline" if gate["passed"] is None
                                                        else "STOP"),
                         f"{roundtrip['identical']}/{roundtrip['clips']} "
                         f"({100 * roundtrip['identical'] / roundtrip['clips']:.2f}%), minimum "
                         f"{100 * roundtrip['minimum']:.0f}%; "
                         + (f"failures: {failures}" if failures else "no failures"),
                         ", ".join(f"{source} {_cell(value)}"
                                   for source, value in sorted(per[scale].items()))])
    stops = [f"**{gate['model']}** stopped: {gate['stop'].rstrip('.')}."
             for name, gate in gates.items() if name != "parity" and gate.get("stop")]
    return ["## The gates, in the order they ran", "",
            "The card gate was replaced by the reference-runtime parity gate (owner approved",
            "architect r4); the card gate's two runs stay here as records, not as verdicts.", "",
            _table(["gate", "what it ran", "result", "round-trip", "character PER at the "
                    "pinned scale"], rows), *stops, ""]


def _verdict(record: Mapping) -> list[str]:
    verdict = record["verdict"]
    rows = []
    for name, row in verdict["correct_side"].items():
        rows.append([name, _cell(row["teacher"]), _cell(row["candidate"]),
                     _cell(row["zipformer"]), _cell(row["gap"]), _cell(row["target"]),
                     "closed" if row["closed"] else "**not closed**"])
    catch = []
    for name, row in verdict["catch_side"].items():
        catch.append([name, _cell(row["zipformer"]), _cell(row["candidate"]),
                      _cell(row["bar"]), "pass" if row["passed"] else "**fail**"])
    return ["## The verdict", "",
            f"**{verdict['verdict']}** — the pre-registered rule, read on the `checks-w1` arm.",
            "",
            verdict["rule"] + ".", "",
            "### The correct side (lower is better)", "",
            _table(["metric", "teacher", "candidate", "zipformer", "gap", "zipformer must reach",
                    "result"], rows),
            "### The catch side", "",
            _table(["metric", "zipformer", "candidate", "bar", "result"], catch),
            f"Correct side: {'passes' if verdict['correct_passed'] else 'fails'}. "
            f"Catch side: {'passes' if verdict['catch_passed'] else 'fails'}.", ""]


def _sets(record: Mapping) -> list[str]:
    arms = record["arm_map"]
    metrics = sorted(next(iter(arms.values())))
    rows = [[metric] + [f"`{arms[model][metric]}`" for model in
                        ("base", "zipformer", "r2_candidate_ema", "c95")] for metric in metrics]
    return ["## The sets and the arms", "",
            "Every metric reads one arm per model, fixed before any decode "
            "(`training.zipformer_decode.metric_arm`); zipformer never writes `stream_b0`.", "",
            _table(["metric", "base", "zipformer", "r2_candidate_ema", "c95"], rows)]


def _disjointness(record: Mapping) -> list[str]:
    dis = record["disjointness"]
    plan = dis["plan"]
    tlog = dis["tlog"]
    rows = [[("same_group (of verdict)" if name == "same_group" else name), str(count)]
            for name, count in sorted(plan.items())]
    rows.extend([["clips screened", str(dis["clips"])],
                 ["tlog roles screened", str(dis["roles"])],
                 ["tlog rows", str(tlog["rows"])],
                 ["tlog indexed rows", str(tlog["indexed_rows"])],
                 ["tlog unfingerprinted rows", str(tlog["unfingerprinted_rows"])],
                 ["tlog rows the round-2 run read", str(tlog["consumed"]["rows"])],
                 ["tlog pool rows (tlog.training)", str(tlog["training"]["rows"])]])
    return ["## Disjointness", "",
            f"**{dis['verdict']}** benchmark clips carry the verdict; the {dis['trained']} the "
            f"candidate trained on are reported apart, {dis['same_group']} share a group (they "
            "stay inside the verdict set and are read apart below), and "
            f"{dis['sealed']} sealed clips were dropped before any decode. The manifest's "
            f"{dis['benchmark']['rows']} rows hold {dis['benchmark']['duplicate_rows']} verbatim "
            f"duplicate, collapsed to the {dis['benchmark']['clips']} clips screened. No "
            "benchmark audio is committed; the screen is by fingerprint and name, never by "
            "listening.", "",
            f"The candidate's \"trained on\" set is rebuilt from the committed consumed log — "
            f"the {tlog['consumed']['rows']:,} rows the round-2 run actually read — not "
            f"`tlog.training`'s {tlog['training']['rows']:,}-row pool: a pool row the run never "
            "read is not exposure (architect r3, D3).", "",
            _table(["plan", "clips"], rows),
            _name_screen(dis["name_screen"]), ""]


def _name_screen(screen: Mapping) -> str:
    parts = []
    for name, row in screen.items():
        tadabur = row.get("tadabur")
        parts.append(f"{name}: {row['reciter']}"
                     + (f", a Tadabur reciter ({tadabur['tadabur_id']}, "
                        f"{len(tadabur['uses'])} uses)" if tadabur else ""))
    return "Reciter-name screen, per source: " + "; ".join(parts) + "."


def _correct(record: Mapping) -> list[str]:
    qdat = record["qdat"]
    rows = []
    for model, row in qdat["models"].items():
        rows.append([model, _cell(row["point"]) + _interval(row),
                     _counts(row)])
    diffs = []
    for name, row in qdat["comparisons"].items():
        diffs.append([name, _cell(row["point"]) + _interval(row)])
    benchmark = record["benchmark"]
    sources = []
    for source, rows_ in benchmark["sources"].items():
        for model, errors in rows_.items():
            if model == "clips":
                continue
            sources.append([source, model,
                            _cell(errors["consonant"]["error"]) +
                            _interval(errors["consonant"]),
                            _cell(errors["haraka"]["error"]) + _interval(errors["haraka"])])
    sensitivity = benchmark["sensitivity"]
    split_rows = [[model, _cell(row["with"]["consonant"]["error"]),
                   _cell(row["without"]["consonant"]["error"]),
                   _cell(row["with"]["haraka"]["error"]),
                   _cell(row["without"]["haraka"]["error"])]
                  for model, row in sensitivity["models"].items()]
    return ["## The correct side", "",
            "### qdat: all-cause false flags per 1,000 graded words", "",
            "The app outcome, replayed through Muraja's own engine at the shipped default. "
            "Zipformer is graded from `checks-w1`, ours from their recorded checks.", "",
            _table(["arm", "per 1,000", "flagged/graded"], rows),
            _table(["paired difference", "per 1,000"], diffs),
            "### The benchmark: per-class phoneme error", "",
            f"{benchmark['clips']['scored']} of the {benchmark['clips']['verdict']} verdict clips "
            "have a phonetizer reference (the "
            f"{len(benchmark['clips']['unsupported'])} Quraysh ayat the phonetizer cannot read are "
            "named in the record); the reference is the phonetizer over the ayah's Uthmani words, "
            "the same realized reference ours are scored against. Clusters are surahs. "
            "tlog_holdout is the verdict source; everyayah_heldout and qul_alnufais are "
            "report-only.", "",
            _table(["source", "model", "consonant error %", "haraka error %"], sources),
            f"Sensitivity (architect r3): the {sensitivity['clips']} tlog_holdout verdict clips "
            "that share a group with a training row, read with them and without them "
            f"({sensitivity['without_clips']} clips).", "",
            _table(["model", "consonant with", "consonant without", "haraka with",
                    "haraka without"], split_rows)]


def _catch(record: Mapping) -> list[str]:
    edits = record["edits"]
    rows = []
    for role in ("edit", "decoy"):
        for model, row in edits["arms"][role].items():
            rows.append([role, model, _cell(row["point"]) + _interval(row),
                         _counts(row)])
    ship = record["ship_a"]
    ship_rows = []
    for arm, row in ship["mistakes_flagged"]["models"].items():
        ship_rows.append([arm, _cell(row["point"]) + _interval(row),
                          _counts(row)])
    return ["## The catch side", "",
            "### The synthetic edits", "",
            "An edit is heard when the decode spells the label at the carrier; a decoy is left "
            "unchanged when it spells the prescribed letter. Paired by the edit pair.", "",
            _table(["role", "model", "rate %", "count"], rows),
            "### Ship A's mistake sites flagged", "",
            f"On the {ship['mistakes']} mistake sites (of {ship['sites']} sites) in the items the "
            "candidate's committed cache holds; the candidate's cache covers 363 of the 512 "
            "Ship A items, so 46 of its 75 mistake sites are read.", "",
            _table(["arm", "flagged %", "flagged/sites"], ship_rows)]


def _commit(record: Mapping) -> list[str]:
    commit = record["commit"]

    def bounds(row) -> str:
        interval = row.get("interval") or row
        return f" [{_cell(interval['lower'])}, {_cell(interval['upper'])}]"

    def side(section: Mapping) -> list[list[str]]:
        rates = section["rates"]
        models = sorted(rates["empty_slot_haraka"]["models"])

        def cell(metric: str, model: str) -> str:
            row = rates[metric]["models"][model]
            return (f"{_cell(row['point'])}{bounds(row)} "
                    f"({row['num']:.0f}/{row['den']:.0f})")

        return [[model] + [cell(metric, model) for metric in
                           ("empty_slot_haraka", "empty_slot_sukun", "commit_rate",
                            "committed_accuracy")] for model in models]

    def percent(value):
        return value * 100 if isinstance(value, (int, float)) else value

    agreement = [[model, _cell(percent(row["point"])) + bounds({
                     "lower": percent(row["lower"]), "upper": percent(row["upper"])}),
                  f"{row['num']:.0f}/{row['den']:.0f} teacher units"]
                 for model, row in sorted(
                     commit["correct_side"]["rates"].get("teacher_agreement", {}).items())]
    header = ["model", "empty haraka slot %", "empty sukun slot %", "commit rate %",
              "committed accuracy %"]
    correct = commit["correct_side"]
    catch = commit["catch_side"]
    return ["## Commit, empty slots and teacher agreement (step 6)", "",
            commit["rule"] + ".", "",
            "### The correct side: the benchmark's verdict clips", "",
            f"{correct['clips']} clips with a phonetizer reference; a sukun slot is a carrier "
            "the mushaf writes with no haraka, so an empty one is the expected form.", "",
            _table(header, side(correct)),
            "### The catch side: the 150 edits", "",
            f"Each edit's own labelled reference; {catch['items']} items, paired by edit.", "",
            _table(header, side(catch)),
            "### Teacher agreement (our students only, a clone diagnostic)", "",
            "Share of the teacher's units a student reproduces after projection onto the "
            "teacher's vocabulary; zipformer is not scored this way.", "",
            _table(["student", "agreement %", "units"], agreement)]


def _match(record: Mapping) -> list[str]:
    match = record["match_rule"]
    rows = []
    for name, row in match["rows"].items():
        rows.append([name, _cell(row["point"]) + _interval(row),
                     "contains 0" if row["interval"]["lower"] <= 0 <= row["interval"]["upper"]
                     else "excludes 0"])
    return ["## The owner's match rule", "",
            match["rule"] + ".", "",
            _table(["metric", "single-stream minus checks-w1", "interval"], rows),
            ("The interval contains zero on both: one stream suffices in the app, and the "
             "verdict is unchanged." if match["matches"] else
             "The interval excludes zero: `checks-w1` stands as the fair comparison, at its "
             "compute cost below."), ""]


def _diversity(record: Mapping) -> list[str]:
    diversity = record["look_diversity"]
    rows = [[arm, _cell(row["words"]), _cell(row["flagged"]),
             _cell(row["multi_look_share"]), _cell(row["rescue_rate"]),
             _cell(row["ratchet_gain"])] for arm, row in diversity["qdat"].items()]
    ship = [[arm, _cell(row["graded"]), _cell(row["flagged_any"]),
             _cell(row["hidden_catches"]), _cell(row["hidden_rate"])]
            for arm, row in diversity["ship_a"].items()]
    return ["## Look diversity (explanation, never a gate)", "",
            "Muraja keeps each word's best grade across its looks. A model that is right on every "
            "look has no rescue and no hidden catch; a noisy one has both, so nothing here is a "
            "goal in itself. Rescue rate is the share of qdat words flagged by at least one look "
            "whose kept grade is correct; ratchet gain is the flagged words under the recorded "
            "checks minus those under one whole-item decode.", "",
            _table(["qdat arm", "words", "flagged", "multi-look %", "rescue %", "ratchet gain"],
                   rows),
            "Ship A's mistake sites: caught by no look once the ratchet keeps the best grade.", "",
            _table(["arm", "graded", "flagged by any look", "hidden catches", "hidden %"], ship)]


def _compute(record: Mapping) -> list[str]:
    compute = record["compute"]
    rows = [[arm, _cell(row["decoded_audio_seconds_per_audio_second"]),
             _cell(row["inferences_per_audio_second"]),
             _cell(row.get("onnx_chunk_calls_per_audio_second"))]
            for arm, row in compute["arms"].items()]
    measured = [[name, _cell(row["items"]), _cell(row["audio_seconds"]),
                 _cell(row["decoded_audio_seconds"]), _cell(row["wall_seconds"])]
                for name, row in compute["measured"].items()]
    probe = record["probe"]
    return ["## Compute", "",
            "Decoded audio per audio-second and calls per audio-second, from the check schedule "
            "(no measurement): ours is a 5 s window plus its previews re-decoded per check; "
            "`checks-w1` is the same schedule with a fresh 1 s-warm-started inference per check "
            "plus the card's 1.05 s flush. ONNX chunk calls are the decoded audio divided by the "
            "card's 0.48 s chunk.", "",
            _table(["arm", "decoded audio s / audio s", "inferences / audio s",
                    "ONNX chunk calls / audio s"], rows),
            f"The timing probe measured {_cell(probe['measured_rate'])} audio-seconds per "
            f"wall-second on 20 qdat items and projected {_cell(probe['projected_hours'])} h for "
            f"the batch, inside the {_cell(probe['horizon_hours'])} h horizon.", "",
            _table(["job", "items", "audio s", "decoded audio s", "wall s"], measured)]


def _report_only(record: Mapping) -> list[str]:
    report = record["report_only"]
    rows = []
    for model, errors in report["qdat_per_class"].items():
        rows.append([model, _cell(errors["consonant"]["error"]),
                     _cell(errors["haraka"]["error"])])
    ship = []
    for arm, row in report["ship_a_whole_item"].items():
        if arm == "harness":
            continue
        ship.append([arm, f"{row['mistakes']['flagged']}/{row['mistakes']['den']}",
                     f"{row['correct']['flagged']}/{row['correct']['den']}"])
    return ["## Report only: the ratchet-free lines", "",
            report["rule"] + ".", "",
            "qdat's whole-item per-class error against the mushaf (reporters without Muraja's "
            "engine):", "",
            _table(["model", "consonant error %", "haraka error %"], rows),
            "Ship A's whole-item outcomes (single-decode approximation):", "",
            _table(["model", "mistake sites flagged", "correct sites flagged"], ship)]


def _exposure(record: Mapping) -> list[str]:
    exposure = record["exposure"]
    rows = []
    for model, corpora in exposure["models"].items():
        for corpus, row in corpora.items():
            rows.append([model, corpus, _cell(row["share"]), _cell(row["exposed"]),
                         _cell(row["reciters"])])
    return ["## Exposure", "",
            exposure["rule"] + ".", "",
            _table(["model", "edit corpus", "reciters exposed %", "exposed", "reciters"], rows)]


def _notes(record: Mapping) -> list[str]:
    return ["## Notes a reader needs beside the verdict", "",
            "**The ratchet treats zipformer differently.** Ours re-decode every window from "
            "scratch, so a word gets several looks; the `checks-w1` arm gives zipformer the same "
            "shape (one fresh inference per check, 1 s of warm state, warm-up emissions "
            "discarded, the 1.05 s flush kept). It is the pre-registered verdict arm; the "
            "single-stream `checks` and the windows-only variant are report-only.", "",
            "**W = 1 s** is fixed before any verdict set was decoded: it is the hop the app has "
            "just committed, so a deployment keeps one extra hop of buffer; zipformer's left "
            "context is about 5.1 s, so a much longer warm-up would converge on the single "
            "stream and lose the looks; and #148 measured 1 s of left context as outcome-neutral "
            "for a model of our kind.", "",
            "**The single-stream `checks` arm is causal, not sliced from the future.** An "
            "emission's text depends on audio up to the end of its chunk; offline slicing "
            "changes when it would arrive (by at most one 0.48 s call), not what it says.", "",
            "**Neither `likely_hallucination` nor `strip_padding_artifacts` is applied.** Both "
            "guard our model's zero-padded, zero-state windows; zipformer never decodes a padded "
            "window, and applying them would delete genuine edge letters.", "",
            "**Both card-gate runs are v1-protocol, and both predate the repair.** The gate's "
            "round-trip is the card's own v1 tokenizer rule, and both runs decoded with the "
            "zero-padded final chunk the diagnosis round removed. v3.2's numbers are a baseline "
            "(the card's table is v3's, which never appears in a comparison set), and v3's STOP "
            "(570/577 = 98.79%, 4 of 7 failures a rule-segmentation the longest-match stand-in "
            "invents) is kept as the record of what that decoder did, not re-run here. The "
            "reference-runtime parity gate replaced them, and it is the one that decides.", "",
            "**The int8 export is a numerics line only.** Its single piece of evidence is the "
            "identity's pinned SHA-256; no int8 decode is committed, compared or used, and no "
            "call in this screen loads it.", "",
            "**qdat_bench is not read.** Its 159 clips are qdat's own bytes, so their decodes "
            "are qdat's; only its expert `phonetic_transcript` would add, and that read needs "
            "the gated Hub token, which lives on cuda-dev. The qdat side scores every model "
            "against the phonetizer reference over the mushaf, as the other readouts do.", "",
            "**What the screen cannot separate.** qdat and the benchmark's tlog_holdout carry "
            "zipformer's known text prior (its card admits 39.5% of planted haraka mistakes "
            "reported, and ikhfnaa written on 81 of 94 plain-noon clips); the catch side is "
            "where that shows, and it is why the verdict is read on it.", ""]


def render(record: Mapping) -> str:
    """The page: header, verdict, then the gates, sets, disjointness, both sides, the match
    rule, the explanation tables and the notes."""
    return "\n".join([HEADER, *_verdict(record), *_gates(record), *_sets(record),
                      *_disjointness(record), *_correct(record), *_catch(record),
                      *_commit(record), *_match(record), *_diversity(record), *_compute(record),
                      *_report_only(record), *_exposure(record), *_notes(record)]).rstrip() + "\n"
